// Builds the demo catalog and the Supabase seed from the collected price files.
// Input:  data/catalog/*.json (one file per research batch) and data/catalog/specs.json (Star Tech spec tables)
// Output: src/data/catalog.generated.ts and supabase/seed.sql
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = "data/catalog";
const AXES = ["chip", "ram", "storage", "size", "connectivity", "edition", "color"];
const DEFAULT_CATEGORY = { mobile: "mobile", watch: "watch" };

const slugify = (text) =>
  text
    .toLowerCase()
    .replace(/["'″]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
const hostOf = (url) => new URL(url).hostname.replace(/^www\./, "");
const httpUrl = (url) => (typeof url === "string" && /^https?:\/\//i.test(url) ? url : null);
const sql = (value) => (value === null || value === undefined ? "null" : typeof value === "number" || typeof value === "boolean" ? String(value) : `'${String(value).replace(/'/g, "''")}'`);

const files = readdirSync(DIR).filter((f) => f.endsWith(".json") && f !== "specs.json");
const specsCache = (() => {
  try {
    return JSON.parse(readFileSync(join(DIR, "specs.json"), "utf8"));
  } catch {
    return {};
  }
})();

const sellers = new Map();
const products = [];
const offers = [];

for (const file of files) {
  const batch = JSON.parse(readFileSync(join(DIR, file), "utf8"));
  for (const site of batch.sites ?? []) {
    const website = httpUrl(site.website);
    if (!website) continue;
    const host = hostOf(website);
    if (!sellers.has(host)) sellers.set(host, { name: site.name, website: website.endsWith("/") ? website : `${website}/`, note: site.note ?? null });
  }
  for (const item of batch.products ?? []) {
    const category = item.category ?? DEFAULT_CATEGORY[batch.category];
    if (!category) throw new Error(`${file}: ${item.name} has no category`);
    const slug = slugify(`${item.brand} ${item.name}`);
    if (products.some((p) => p.slug === slug)) continue;
    const variants = item.variants.map((v, i) => ({
      id: `${slug}~v${i + 1}`,
      label: v.label,
      attributes: Object.fromEntries(Object.entries(v.attributes ?? {}).filter(([k, value]) => AXES.includes(k) && value)),
      officialPrice: Number.isInteger(v.officialPrice) ? v.officialPrice : null,
    }));
    const specs = item.specsSource ? specsCache[item.specsSource] ?? [] : [];
    const kept = [];
    for (const offer of item.offers ?? []) {
      const url = httpUrl(offer.url);
      const variant = variants.find((v) => v.label === offer.variant) ?? (variants.length === 1 ? variants[0] : null);
      if (!url || !variant || !Number.isInteger(offer.price) || offer.price <= 0) continue;
      const host = hostOf(url);
      if (!sellers.has(host)) sellers.set(host, { name: offer.site, website: `https://${new URL(url).hostname}/`, note: null });
      const condition = offer.condition === "unofficial" || offer.condition === "used" ? offer.condition : "official";
      const key = `${variant.id}|${host}|${condition}`;
      const existing = kept.find((o) => o.key === key);
      if (existing && existing.price <= offer.price) continue;
      if (existing) kept.splice(kept.indexOf(existing), 1);
      kept.push({
        key,
        variantId: variant.id,
        host,
        condition,
        region: offer.region || null,
        price: offer.price,
        oldPrice: Number.isInteger(offer.oldPrice) && offer.oldPrice > offer.price ? offer.oldPrice : null,
        inStock: typeof offer.inStock === "boolean" ? offer.inStock : null,
        url,
        checkedAt: offer.checkedAt ?? new Date().toISOString().slice(0, 10),
      });
    }
    offers.push(...kept);
    const shops = new Set(kept.map((o) => o.host)).size;
    products.push({
      id: slug,
      slug,
      name: item.name,
      brand: item.brand,
      category,
      releaseYear: Number.isInteger(item.releaseYear) ? item.releaseYear : null,
      popularity: Math.min(100, 50 + shops * 8 + (item.popular ? 10 : 0)),
      variants,
      images: (item.images ?? []).map(httpUrl).filter(Boolean).slice(0, 5),
      colors: item.colors ?? [],
      regions: [...new Set(kept.map((o) => o.region).filter(Boolean))],
      specs,
      specsSource: httpUrl(item.specsSource),
    });
  }
}

const sellerList = [...sellers.entries()].map(([host, s]) => ({ id: host, ...s }));
const usedHosts = new Set(offers.map((o) => o.host));
const activeSellers = sellerList.filter((s) => usedHosts.has(s.id));

const ts = `// Generated by scripts/import-catalog.mjs from data/catalog/*.json. Do not edit by hand.
import type { Offer, Product, Seller } from "@/types/catalog";

export const catalogSellers: Seller[] = ${JSON.stringify(
  activeSellers.map((s) => ({ id: s.id, name: s.name, kind: "website", website: s.website, phone: null, whatsapp: null, facebook: null, area: null, verified: true, active: true })),
  null,
  1,
)};

export const catalogProducts: Product[] = ${JSON.stringify(products, null, 1)};

export const catalogOffers: Offer[] = ${JSON.stringify(
  offers.map((o, i) => ({
    id: `o${i + 1}`,
    variantId: o.variantId,
    sellerId: o.host,
    condition: o.condition,
    region: o.region,
    price: o.price,
    oldPrice: o.oldPrice,
    inStock: o.inStock,
    url: o.url,
    source: "site",
    published: true,
    checkedAt: new Date(`${o.checkedAt}T09:00:00+06:00`).toISOString(),
  })),
  null,
  1,
)};
`;
writeFileSync("src/data/catalog.generated.ts", ts);

const lines = ["-- Generated by scripts/import-catalog.mjs from data/catalog/*.json. Safe to run more than once.", ""];
for (const s of activeSellers) {
  lines.push(
    `insert into sellers (name, kind, website, verified) select ${sql(s.name)}, 'website', ${sql(s.website)}, true where not exists (select 1 from sellers where website ilike ${sql(`%${s.id}%`)});`,
  );
}
lines.push("");
for (const p of products) {
  const pid = `md5(${sql(`product:${p.slug}`)})::uuid`;
  lines.push(
    `insert into products (id, slug, name, brand, category, release_year, popularity, images, colors, regions, specs, specs_source) values (${pid}, ${sql(p.slug)}, ${sql(p.name)}, ${sql(p.brand)}, ${sql(p.category)}, ${sql(p.releaseYear)}, ${p.popularity}, ${sql(`{${p.images.map((x) => `"${x}"`).join(",")}}`)}, ${sql(`{${p.colors.map((x) => `"${x}"`).join(",")}}`)}, ${sql(`{${p.regions.map((x) => `"${x}"`).join(",")}}`)}, ${sql(JSON.stringify(p.specs))}::jsonb, ${sql(p.specsSource)}) on conflict (slug) do nothing;`,
  );
  p.variants.forEach((v, position) => {
    lines.push(
      `insert into variants (id, product_id, label, attributes, official_price, position) values (md5(${sql(`variant:${v.id}`)})::uuid, ${pid}, ${sql(v.label)}, ${sql(JSON.stringify(v.attributes))}::jsonb, ${sql(v.officialPrice)}, ${position}) on conflict (id) do nothing;`,
    );
  });
}
lines.push("");
for (const o of offers) {
  lines.push(
    `insert into offers (variant_id, seller_id, condition, region, price, old_price, in_stock, url, source, checked_at) select md5(${sql(`variant:${o.variantId}`)})::uuid, s.id, ${sql(o.condition)}, ${sql(o.region)}, ${o.price}, ${sql(o.oldPrice)}, ${sql(o.inStock)}, ${sql(o.url)}, 'site', ${sql(`${o.checkedAt} 09:00+06`)} from sellers s where s.website ilike ${sql(`%${o.host}%`)} limit 1 on conflict (variant_id, seller_id, condition) do nothing;`,
  );
}
writeFileSync("supabase/seed.sql", `${lines.join("\n")}\n`);

console.log(`${products.length} products, ${products.reduce((n, p) => n + p.variants.length, 0)} variants, ${offers.length} offers, ${activeSellers.length} shops`);
for (const p of products) {
  const shops = new Set(offers.filter((o) => p.variants.some((v) => v.id === o.variantId)).map((o) => o.host)).size;
  if (shops < 3) console.log(`  fewer than 3 shops: ${p.brand} ${p.name} (${shops})`);
}
