import { readFile, writeFile } from "node:fs/promises";
import { nearestArea } from "./places/geo.mjs";
import { mergePlaces } from "./places/merge.mjs";
import { fetchOverpass, osmPlaces } from "./places/osm.mjs";
import { fetchOverture } from "./places/overture.mjs";
import { seedSql } from "./places/seed-sql.mjs";

const readJson = async (path) => JSON.parse(await readFile(new URL(path, import.meta.url), "utf8"));
const categories = await readJson("../src/data/categories.json");
const purposes = await readJson("../src/data/purposes.json");

const [elements, overture] = await Promise.all([fetchOverpass(), fetchOverture()]);
const osm = osmPlaces(elements);
const osmPhones = osm.places.filter((p) => p.phone).length;
const merged = mergePlaces(osm.places, overture.places);
const places = merged.places.map((p) => ({ ...p, area: nearestArea(p, osm.areas) }));

const header = [
  `Generated by scripts/import-places.mjs on ${new Date().toISOString().slice(0, 10)}.`,
  "Re-run: npm run data:places, then apply with: npx supabase db query --linked -f supabase/seed.sql",
  "",
  "Sources and licenses:",
  "OpenStreetMap — © OpenStreetMap contributors, ODbL 1.0 — https://www.openstreetmap.org/copyright",
  `Overture Maps Places ${overture.release} — © Overture Maps Foundation — https://docs.overturemaps.org/attribution/`,
  ...overture.licenses.map((license) => `  ${license}`),
];
await writeFile(new URL("../supabase/seed.sql", import.meta.url), seedSql({ header, categories, purposes, places }));

const filledOsm = merged.filled.filter((f) => f.target.source === "osm");
const count = (list, category) => list.filter((p) => p.category === category).length;
console.log(`supabase/seed.sql: ${places.length} places — ${osm.places.length} OSM + ${merged.added.length} Overture ${overture.release}`);
console.log(
  `Overture: ${overture.places.length} in our categories, ${merged.filled.length} matched by name, ` +
    `${merged.skipped.length} dropped as same-spot duplicates`,
);
console.log(
  `phones: ${osmPhones} on OSM rows → +${filledOsm.filter((f) => f.gained.phone).length} filled from Overture, ` +
    `+${merged.added.filter((p) => p.phone).length} on new Overture rows · ` +
    `websites: +${filledOsm.filter((f) => f.gained.website).length} filled, +${merged.added.filter((p) => p.website).length} new`,
);
console.table(
  Object.fromEntries(
    categories.map((c) => [c.id, { osm: count(osm.places, c.id), overture: count(merged.added, c.id), total: count(places, c.id) }]),
  ),
);
