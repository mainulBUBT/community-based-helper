import { readFile, writeFile } from "node:fs/promises";

const readJson = async (path) => JSON.parse(await readFile(new URL(path, import.meta.url), "utf8"));

const categories = await readJson("../src/data/categories.json");
const purposes = await readJson("../src/data/purposes.json");
const places = await readJson("../src/data/sample-places.json");

const WEEK = [0, 1, 2, 3, 4, 5, 6];
const text = (value) => (value == null ? "null" : `'${String(value).replaceAll("'", "''")}'`);
const placeId = (slug) => (slug ? `md5('place:${slug}')::uuid` : "null");
const verifiedAt = (days) => (days == null ? "null" : `now() - interval '${days} days'`);

const categoryRows = categories.map(
  (c, i) => `  (${text(c.id)}, ${text(c.name)}, ${text(c.short)}, ${c.isMarket}, ${i + 1})`,
);

const purposeRows = purposes.map((p, i) => `  (${text(p.id)}, ${text(p.name)}, ${i + 1})`);

const placeRows = places.map(
  (p) =>
    `  (${placeId(p.id)}, ${placeId(p.parent)}, ${text(p.kind)}, ${text(p.category)}, ${text(p.name)}, ` +
    `${text(p.area)}, ${text(p.floor)}, ${text(p.unit)}, ${p.lat}, ${p.lng}, ${text(p.phone)}, ${p.open24h}, ` +
    `${text(p.status ?? "confirmed")}, ${verifiedAt(p.verifiedDaysAgo)})`,
);

const placePurposeRows = places.flatMap((p) => p.purposes.map((id) => `  (${placeId(p.id)}, ${text(id)})`));

const hourRows = places.flatMap((p) =>
  WEEK.filter((day) => !p.closedOn?.includes(day)).flatMap((day) =>
    p.hours.map(([opens, closes]) => `  (${placeId(p.id)}, ${day}, ${opens}, ${closes})`),
  ),
);

const sql = `-- Generated by scripts/build-seed.mjs from src/data. Edit the JSON, then run: npm run seed:sql

insert into public.categories (id, name_bn, short_bn, is_market, sort_order) values
${categoryRows.join(",\n")}
on conflict (id) do update set
  name_bn = excluded.name_bn,
  short_bn = excluded.short_bn,
  is_market = excluded.is_market,
  sort_order = excluded.sort_order;

insert into public.purposes (id, name_bn, sort_order) values
${purposeRows.join(",\n")}
on conflict (id) do update set name_bn = excluded.name_bn, sort_order = excluded.sort_order;

insert into public.places (id, parent_id, kind, category_id, name, area, floor, unit, lat, lng, phone, open_24h, status, verified_at) values
${placeRows.join(",\n")}
on conflict (id) do nothing;

insert into public.place_purposes (place_id, purpose_id) values
${placePurposeRows.join(",\n")}
on conflict do nothing;

insert into public.opening_hours (place_id, weekday, opens_min, closes_min) values
${hourRows.join(",\n")}
on conflict do nothing;
`;

await writeFile(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`supabase/seed.sql: ${places.length} places, ${purposes.length} purposes, ${hourRows.length} hour rows`);
